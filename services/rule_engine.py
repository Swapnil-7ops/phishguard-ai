def evaluate_rules(features: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Evaluate all registered security rules against an extracted feature dictionary.

    Args:
        features: Dictionary of 25 numerical features.

    Returns:
        List of triggered rule dictionaries formatted for presentation and scoring.
    """
    triggered = []
    for rule in RULES:
        try:
            if rule["detect"](features):
                triggered.append({
                    "rule_id": rule["rule_id"],
                    "name": rule["name"],
                    "severity": rule["severity"],
                    "score_impact": rule["score_impact"],
                    "description": rule["description"]
                })
        except Exception:
            continue
    return triggered
